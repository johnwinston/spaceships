    # Default character width and spacing
    CHAR_WIDTH = 18
    CHAR_HEIGHT = 21
    CHAR_SPACING = 6
    WORD_SPACING = 12
    
    @classmethod
    def render_text(cls, text: str, x: float, y: float, size: float = 8.0) -> List[str]:
        """Render text as SVG path elements.
        
        Args:
            text: Text string to render
            x: Starting X position
            y: Baseline Y position (bottom of text)
            size: Font size in pixels
            
        Returns:
            List of SVG path elements
        """
        paths = []
        scale = size / cls.CHAR_HEIGHT
        cursor_x = x
        
        for char in text:
            if char == ' ':
                cursor_x += cls.WORD_SPACING * scale
                continue
                
            if char not in cls.GLYPHS:
                char = char.upper()
                
            if char in cls.GLYPHS:
                strokes = cls.GLYPHS[char]
                
                for stroke in strokes:
                    if not stroke:
                        continue
                        
                    # Build path data
                    path_data = []
                    for i, (px, py) in enumerate(stroke):
                        # Scale and position
                        sx = cursor_x + px * scale
                        sy = y - (cls.CHAR_HEIGHT - py) * scale  # Flip Y and adjust to baseline
                        
                        if i == 0:
                            path_data.append(f"M {sx:.2f},{sy:.2f}")
                        else:
                            path_data.append(f"L {sx:.2f},{sy:.2f}")
                    
                    if path_data:
                        paths.append(f'    <path d="{" ".join(path_data)}" '
                                   f'stroke="black" stroke-width="0.5" fill="none"/>')
                
                cursor_x += (cls.CHAR_WIDTH + cls.CHAR_SPACING) * scale
        
        return paths
