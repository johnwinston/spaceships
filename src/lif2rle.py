"""Headless Life 1.05 -> RLE conversion.

Replaces the Golly-based step: ``src/automons.py`` ran inside Golly purely
to re-save ntzfind's Life 1.05 output as RLE.  This does the same thing
with the project RLE codec, no GUI required.

``auto_ntzfind`` writes a small dialect of Life 1.05:

    #Life 1.05
    #b2ce3aiy/s2ace3i     <- the rule
    #Period p4
    ..**..
    .*..*.

Body rows are ``.`` (dead) and ``*`` (alive), top to bottom.

Output lands in the ``rles/<period>/`` layout that ``rle2apgcode`` reads,
one ``<stem>.rle`` per ``<stem>.lif``.

Usage:
    python -m src.lif2rle --periods 4 5 6 7
"""
import argparse
import os
import re

from . import config
from . import rle as rle_codec

# b<...>/s<...>, as generated by auto_ntzfind (lowercase Hensel INT).
_RULE_RE = re.compile(r"^[bB][0-9a-z-]*/[sS][0-9a-z-]*$")


def parse_life105(text):
    """Parse the auto_ntzfind Life 1.05 dialect into (cells, rule).

    cells is a list of (x, y) live cells; rule is the rule string from
    the header.  Raises ValueError on files this dialect can't describe.
    """
    rule = None
    cells = []
    y = 0
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("#"):
            content = line[1:].strip()
            if content.upper().startswith("R "):  # standard #R rule line
                content = content[2:].strip()
            lowered = content.lower()
            if lowered.startswith("life") or lowered.startswith("period"):
                continue
            if rule is None and _RULE_RE.match(content):
                rule = content
            continue
        for x, ch in enumerate(line):
            if ch == "*":
                cells.append((x, y))
            elif ch != ".":
                raise ValueError(
                    "unexpected character %r in pattern row %d" % (ch, y)
                )
        y += 1
    if rule is None:
        raise ValueError("no rule header found")
    if not cells:
        raise ValueError("no live cells in pattern body")
    return cells, rule


def convert_file(lif_path, out_path):
    """Convert one .lif file to .rle.  Returns the RLE text written."""
    with open(lif_path) as f:
        cells, rule = parse_life105(f.read())
    rle_text = rle_codec.serialize(cells, rule)
    with open(out_path, "w") as f:
        f.write(rle_text + "\n")
    return rle_text


def convert_period(period, base=None):
    """Convert every .lif for ``period`` into rles/<period>/.

    Returns the number of files written; parse failures are reported and
    skipped rather than aborting the batch.
    """
    base = base if base is not None else config.PIPELINE_BASE
    src_dir = os.path.join(base, "ntzfind_patterns", str(period))
    out_dir = os.path.join(base, "rles", str(period))
    if not os.path.isdir(src_dir):
        raise FileNotFoundError("no such pattern directory: %s" % src_dir)
    os.makedirs(out_dir, exist_ok=True)

    written = 0
    for name in sorted(os.listdir(src_dir)):
        if not name.endswith(".lif"):
            continue
        stem = name[: -len(".lif")]
        lif_path = os.path.join(src_dir, name)
        out_path = os.path.join(out_dir, stem + ".rle")
        try:
            convert_file(lif_path, out_path)
        except ValueError as e:
            print("skipping %s: %s" % (lif_path, e))
            continue
        written += 1
    return written


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--periods", nargs="+", required=True)
    args = parser.parse_args()
    for period in args.periods:
        count = convert_period(period)
        print("period %s: wrote %d rle files" % (period, count))


if __name__ == "__main__":
    main()
